import logging
import os
from uuid import uuid4

from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException
from google import genai
from pydantic import BaseModel, Field


# Load settings such as GEMINI_API_KEY from the local .env file.
load_dotenv()

# Send technical error details to the server terminal for debugging.
logging.basicConfig(level=logging.INFO)

# Create our FastAPI backend.
app = FastAPI(title="LLM API Integration")

# Keep the latest five completed exchanges in each conversation.
MAX_HISTORY_TURNS = 5

# Define the chatbot's role and response style.
SYSTEM_INSTRUCTION = (
    "You are a friendly, beginner-friendly AI assistant. "
    "Explain concepts clearly and use practical examples."
)

# Each conversation ID maps to a list of completed exchanges.
# Each exchange stores the user's input and Gemini's response steps.
conversation_histories: dict[str, list[list[dict]]] = {}


class ChatRequest(BaseModel):
    # The message must contain between 1 and 4000 characters.
    message: str = Field(min_length=1, max_length=4000)

    # A client can reuse this ID to continue an earlier conversation.
    # If omitted, the server will generate a new conversation ID.
    conversation_id: str | None = Field(
        default=None, min_length=1, max_length=100
    )


@app.post("/chat")
def chat(request: ChatRequest):
    # Check that the API key has been configured.
    if not os.getenv("GEMINI_API_KEY"):
        raise HTTPException(
            status_code=500,
            detail="Server configuration is missing the Gemini API key.",
        )

    # Continue the supplied conversation, or start a new one.
    conversation_id = request.conversation_id or str(uuid4())

    # Read this conversation's saved exchanges.
    saved_turns = conversation_histories.get(conversation_id, [])

    # Select only recent exchanges for the next model request.
    recent_turns = saved_turns[-MAX_HISTORY_TURNS:]

    # Combine the steps from those previous exchanges.
    input_steps = [
        step
        for turn in recent_turns
        for step in turn
    ]

    # Add the new user message in the format expected by Gemini.
    current_user_step = {
        "type": "user_input",
        "content": [
            {
                "type": "text",
                "text": request.message,
            }
        ],
    }
    input_steps.append(current_user_step)

    # Read the model selected in .env.
    model = os.getenv("GEMINI_MODEL", "gemini-3.5-flash-lite")

    try:
        # Create the Gemini client using the configured API key.
        client = genai.Client()

        # Send the recent history and current message to Gemini.
        # store=False means we manage the history in our application.
        # We repeat the system instruction with each stateless request.
        interaction = client.interactions.create(
            model=model,
            input=input_steps,
            system_instruction=SYSTEM_INSTRUCTION,
            store=False,
        )

        # Extract the final text generated by the model.
        reply = interaction.output_text

        # Treat an empty response as an unsuccessful model request.
        if not reply:
            raise HTTPException(
                status_code=502,
                detail="The AI service returned an empty response. Please try again.",
            )

        # Preserve the complete model steps needed for subsequent requests.
        # The SDK's model_dump() converts each step into dictionary data.
        model_steps = [
            step.model_dump()
            for step in interaction.steps
        ]

        # Save the user message and model steps as one completed exchange.
        completed_turn = [current_user_step, *model_steps]
        updated_history = [*saved_turns, completed_turn]

        # Discard old exchanges beyond the configured history limit.
        conversation_histories[conversation_id] = (
            updated_history[-MAX_HISTORY_TURNS:]
        )

        # Return both the answer and the ID needed for the next message.
        return {
            "conversation_id": conversation_id,
            "reply": reply,
        }

    except HTTPException:
        # Preserve intentional HTTP errors raised above.
        raise

    except Exception:
        # Keep detailed technical errors in the server terminal.
        # Return a clearer message to the client instead.
        logging.exception("Gemini API request failed")

        raise HTTPException(
            status_code=502,
            detail="The AI service could not respond. Please try again.",
        )
import os  # Lets Python read settings stored in environment variables.

from dotenv import load_dotenv  # Loads settings from our local .env file.
from google import genai  # Imports Google's SDK for communicating with Gemini.


def main():
    # Read the API key and model name from the .env file.
    load_dotenv()

    # Check for the API key before making a network request.
    # This gives us a clear message if the configuration is missing.
    if not os.getenv("GEMINI_API_KEY"):
        print("API key missing. Please check your .env file.")
        return

    # Read the model name from .env.
    # The second value is a fallback if GEMINI_MODEL is not configured.
    model = os.getenv("GEMINI_MODEL", "gemini-3.8-flash")

    try:
        # Create the Gemini client.
        # The SDK reads GEMINI_API_KEY from the environment.
        client = genai.Client()

        # Send one simple request to the model.
        # The input is the question or instruction we want Gemini to process.
        response = client.interactions.create(
            model=model,
            input="Explain what an API is in one simple sentence."
        )

        # Print the text generated by Gemini.
        print("\nGemini's response:")
        print(response.output_text)

    except Exception as error:
        # Show a useful diagnostic if the request fails.
        # We are not printing or exposing the API key.
        print("\nThe Gemini request failed.")
        print("Error details:", error)


# Run main() when this file is executed directly.
if __name__ == "__main__":
    main()